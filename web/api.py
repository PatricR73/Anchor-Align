_AUDIO_TTL_S = 60 * 60  # uploaded audio is kept for playback for one hour

# Upload limits: configurable max per-file size, enforced (a) by a middleware
# that rejects a declared Content-Length before the body is consumed, and
# (b) per chunk while streaming the parsed parts to disk - so an oversized
# body never needs to be fully buffered first. UploadFile.file is a
# disk-backed SpooledTemporaryFile past ~1 MB, but .read() would still slurp
# it into RAM (see _stream_to_disk).
MAX_UPLOAD_BYTES = int(os.environ.get("MAX_UPLOAD_BYTES", str(1 << 30)))  # 1 GiB default
_UPLOAD_BUFFER = 1 << 20  # 1 MiB streaming buffer
_MULTIPART_SLACK = 4 << 20  # multipart framing + the small transcript

# Large synthetic fixture — DEV ONLY. The payload JSON is generated by
# web/scripts/make_fixture.py into .cache/fixtures/ (gitignored, so it is
# never part of a build artifact), and the route 404s unless
# ALLOW_FIXTURES=1 is set, so a production deploy cannot reach it.
ALLOW_FIXTURES = os.environ.get("ALLOW_FIXTURES") == "1"
FIXTURE_JSON = REPO_ROOT / ".cache" / "fixtures" / "large.json"
FIXTURE_WAV = REPO_ROOT / ".cache" / "fixtures" / "large.wav"
FIXTURE_GENERATOR = REPO_ROOT / "web" / "scripts" / "make_fixture.py"



@asynccontextmanager
async def lifespan(_: FastAPI) -> typing.AsyncIterator[None]:
    """Warm the default model off the event loop so the first job (and the
    readiness check) does not pay the load. A failed warm-up logs and keeps
    the server up — readiness then reports model_resident=false and the
    first job with that model surfaces the real error."""
    try:
        # _get_adapter only creates the (lazy) adapter — force the actual
        # WhisperModel load so the first job doesn't pay it. _load_model is
        # the adapter's own lazy loader (same project).
        adapter = _get_adapter(DEFAULT_MODEL)
        await asyncio.to_thread(adapter._load_model)  # keep the loop free during load
    except Exception:  # noqa: BLE001 - startup must not die on a model issue
        logger.exception("could not warm faster-whisper model %s", DEFAULT_MODEL)
    yield


